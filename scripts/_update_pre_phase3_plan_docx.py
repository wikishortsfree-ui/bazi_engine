def main() -> int:
    if not DOC_PATH.exists():
        raise FileNotFoundError(DOC_PATH)
    doc = Document(str(DOC_PATH))

    remaining = {old: new for old, new in REPLACEMENTS}
    matched: set[str] = set()

    for para in doc.paragraphs:
        text = para.text
        for old in list(remaining.keys()):
            if old == text.strip():
                para.text = remaining[old]
                matched.add(old)
                del remaining[old]
                break

    # A second pass for "contains" matches (paragraphs with leading bullets / styling whitespace).
    for para in doc.paragraphs:
        for old in list(remaining.keys()):
            if old in para.text:
                para.text = para.text.replace(old, remaining[old])
                matched.add(old)
                del remaining[old]
                break

    if remaining:
        print("WARNING: unmatched paragraphs:")
        for old in remaining:
            print(f"  - {old[:80]}...")

    doc.save(str(DOC_PATH))
    print(f"Updated {DOC_PATH} ({len(matched)}/{len(REPLACEMENTS)} replacements applied).")
    return 0 if not remaining else 1


if __name__ == "__main__":
    raise SystemExit(main())
